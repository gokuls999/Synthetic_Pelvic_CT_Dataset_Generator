"""Per-patient PNG/JPG and metadata.json exports."""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
from PIL import Image

if TYPE_CHECKING:
    from .generate import SyntheticVolume


def _window_to_uint8(slice_hu: np.ndarray, lo: float, hi: float) -> np.ndarray:
    s = np.clip(slice_hu.astype(np.float32), lo, hi)
    s = (s - lo) / max(hi - lo, 1e-6)
    return (s * 255.0).astype(np.uint8)


def write_png_jpg_metadata(vol: "SyntheticVolume",
                           png_dir: Path, jpg_dir: Path, meta_path: Path,
                           cfg: dict) -> None:
    out_cfg = cfg["output"]
    lo, hi = out_cfg["png_window"]

    Z = vol.pixels_hu.shape[0]
    if out_cfg.get("write_png", True):
        png_dir.mkdir(parents=True, exist_ok=True)
    if out_cfg.get("write_jpg", True):
        jpg_dir.mkdir(parents=True, exist_ok=True)

    for i in range(Z):
        img = Image.fromarray(_window_to_uint8(vol.pixels_hu[i], lo, hi), mode="L")
        if out_cfg.get("write_png", True):
            img.save(png_dir / f"slice_{i+1:04d}.png", "PNG")
        if out_cfg.get("write_jpg", True):
            img.save(jpg_dir / f"slice_{i+1:04d}.jpg", "JPEG", quality=92)

    meta = {
        "patient_id": vol.patient_id,
        "region": vol.region,
        "region_id": vol.region_id,
        "sex": "Female",
        "modality": "CT",
        "body_part": "PELVIS",
        "n_slices": int(Z),
        "slice_thickness_mm": float(vol.spacing[0]),
        "pixel_spacing_mm": [float(vol.spacing[1]), float(vol.spacing[2])],
        "hu_window_display": [int(lo), int(hi)],
        "seed": int(vol.seed),
        "manufacturer": out_cfg.get("manufacturer", "SyntheticPelvicCT"),
        "institution": out_cfg.get("institution", "GenAI Pelvic Study"),
        "synthetic": True,
        "notes": "Generated by gen_ai_ct_pelvic. Region label is a morphometric "
                 "pseudo-label, not a biographical attribute.",
    }
    meta_path.parent.mkdir(parents=True, exist_ok=True)
    meta_path.write_text(json.dumps(meta, indent=2))
